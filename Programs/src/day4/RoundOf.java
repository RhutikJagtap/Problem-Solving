package day4;

public class RoundOf {
	
	public static void main(String[] args) {
		float x=323.648388337f;
		double y=123.345678;
		
		System.out.println(x);
		System.out.printf("%.2f",x);
		System.out.println();
		
		System.out.println("==============");
		
		System.out.println(y);
		System.out.printf("%.2f",y);
	}

}
